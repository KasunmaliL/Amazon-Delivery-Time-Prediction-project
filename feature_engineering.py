# Creates features (distance, time-based features) and saves final_features.csv

import pandas as pd
import numpy as np
from math import radians, sin, cos, atan2, sqrt

CLEAN_PATH = "cleaned_data.csv"
OUT_PATH = "final_features.csv"

def haversine(lat1, lon1, lat2, lon2):
    # handle missing gracefully
    try:
        R = 6371.0
        dlat = radians(lat2 - lat1)
        dlon = radians(lon2 - lon1)
        a = sin(dlat/2)**2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon/2)**2
        c = 2 * atan2(sqrt(a), sqrt(1-a))
        return R * c
    except Exception:
        return np.nan

if __name__ == "__main__":
    df = pd.read_csv(CLEAN_PATH)

    # parse times back to datetime where needed
    df["Order_Date"] = pd.to_datetime(df["Order_Date"])
    df["Order_Time"] = pd.to_datetime(df["Order_Time"], errors="coerce")
    df["Pickup_Time"] = pd.to_datetime(df["Pickup_Time"], errors="coerce")

    # Distance
    df["Distance_km"] = df.apply(lambda r: haversine(
        r.get("Store_Latitude"), r.get("Store_Longitude"),
        r.get("Drop_Latitude"), r.get("Drop_Longitude")
    ), axis=1)

    # Time-based features
    df["Order_Hour"] = df["Order_Time"].dt.hour
    df["Order_Day"] = df["Order_Date"].dt.day_name()
    df["Pickup_Delay_Minutes"] = (df["Pickup_Time"] - df["Order_Time"]).dt.total_seconds() / 60.0

    # Weekend and peak indicators
    df["Is_Weekend"] = df["Order_Date"].dt.weekday.isin([5,6]).astype(int)
    df["Is_Peak_Hour"] = df["Order_Hour"].between(16, 19).astype(int)

    # Delivery speed (safe guard divide by zero)
    df["Delivery_Speed_km_per_hr"] = df.apply(lambda r: r["Distance_km"]/r["Delivery_Time"]
                                                if r["Delivery_Time"]>0 else np.nan, axis=1)

    # Save
    df.to_csv(OUT_PATH, index=False)
    print(f"Final features saved to {OUT_PATH}. Rows: {len(df)}")



