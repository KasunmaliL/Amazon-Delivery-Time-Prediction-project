# Loads raw CSV, cleans, and writes cleaned_data.csv

import pandas as pd
import numpy as np
from dateutil import parser

RAW_PATH = "amazon_delivery.csv"
CLEAN_PATH = "cleaned_data.csv"

def load_data(path=RAW_PATH):
    df = pd.read_csv(path)
    return df

def basic_cleaning(df: pd.DataFrame) -> pd.DataFrame:
    # drop exact duplicates
    df = df.drop_duplicates().copy()

    # forward/backward fill then drop remaining NaNs
    df = df.fillna(method="ffill").fillna(method="bfill")
    df = df.dropna()

    # parse dates/times
    df["Order_Date"] = pd.to_datetime(df["Order_Date"], errors="coerce")
    df["Order_Time"] = pd.to_datetime(df["Order_Time"], errors="coerce").dt.time
    df["Pickup_Time"] = pd.to_datetime(df["Pickup_Time"], errors="coerce").dt.time

    # remove rows with missing crucial columns
    df = df.dropna(subset=["Order_Date", "Order_Time", "Pickup_Time"])

    # realistic agent age
    if "Agent_Age" in df.columns:
        df = df[df["Agent_Age"].between(18, 80)]

    # delivery time non-negative
    if "Delivery_Time" in df.columns:
        df = df[df["Delivery_Time"] >= 0]

    df = df.reset_index(drop=True)
    return df

if __name__ == "__main__":
    df = load_data()
    df = basic_cleaning(df)
    df.to_csv(CLEAN_PATH, index=False)
    print(f"Cleaned data saved to {CLEAN_PATH}. Rows: {len(df)}")