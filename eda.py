# Exploratory Data Analysis scripts that produce and save plots into /plots/

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

sns.set(style="whitegrid")

IN_PATH = "final_features.csv"
PLOTS_DIR = "plots"

import os
os.makedirs(PLOTS_DIR, exist_ok=True)

def main():
    df = pd.read_csv(IN_PATH)

    # Delivery time distribution
    plt.figure(figsize=(8,5))
    sns.histplot(df['Delivery_Time'].dropna(), kde=True, bins=30)
    plt.title('Delivery Time Distribution (hours)')
    plt.xlabel('Delivery Time (hours)')
    plt.savefig(f"{PLOTS_DIR}/delivery_time_distribution.png")
    plt.close()

    # Distance vs Delivery Time
    plt.figure(figsize=(8,5))
    sns.scatterplot(x='Distance_km', y='Delivery_Time', data=df)
    plt.title('Distance vs Delivery Time')
    plt.savefig(f"{PLOTS_DIR}/distance_vs_delivery_time.png")
    plt.close()

    # Traffic impact (if encoded or categorical)
    if 'Traffic' in df.columns:
        plt.figure(figsize=(8,5))
        sns.boxplot(x='Traffic', y='Delivery_Time', data=df)
        plt.title('Traffic vs Delivery Time')
        plt.savefig(f"{PLOTS_DIR}/traffic_vs_delivery_time.png")
        plt.close()

    # Weather impact
    if 'Weather' in df.columns:
        plt.figure(figsize=(8,5))
        sns.boxplot(x='Weather', y='Delivery_Time', data=df)
        plt.title('Weather vs Delivery Time')
        plt.savefig(f"{PLOTS_DIR}/weather_vs_delivery_time.png")
        plt.close()

    # Correlation heatmap
    plt.figure(figsize=(10,8))
    sns.heatmap(df.select_dtypes(include=["number"]).corr(), annot=False)
    plt.title('Correlation Heatmap')
    plt.savefig(f"{PLOTS_DIR}/correlation_heatmap.png")
    plt.close()

    print("EDA plots saved to plots/")

if __name__ == '__main__':
    main()