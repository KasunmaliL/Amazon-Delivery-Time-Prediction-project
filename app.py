import streamlit as st
import pandas as pd
from predict import predict_single
from feature_engineering import haversine

st.set_page_config(page_title='Amazon Delivery Time Predictor', layout='wide')

st.title('Amazon Delivery Time Predictor')

st.sidebar.header('Order details')

# Input fields
agent_age = st.sidebar.number_input('Agent Age', min_value=18, max_value=80, value=30)
agent_rating = st.sidebar.number_input('Agent Rating', min_value=1.0, max_value=5.0, value=4.5, step=0.1)
store_lat = st.sidebar.number_input('Store Latitude', value=6.9271)
store_lon = st.sidebar.number_input('Store Longitude', value=79.8612)
drop_lat = st.sidebar.number_input('Drop Latitude', value=6.9275)
drop_lon = st.sidebar.number_input('Drop Longitude', value=79.8615)

order_hour = st.sidebar.slider('Order Hour', 0, 23, 14)
order_day = st.sidebar.selectbox('Order Day', ['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'])

weather = st.sidebar.selectbox('Weather', ['Sunny','Cloudy','Rainy','Storm'])
traffic = st.sidebar.selectbox('Traffic', ['Low','Moderate','High'])
vehicle = st.sidebar.selectbox('Vehicle', ['Bike','Motorbike','Car','Van'])
area = st.sidebar.selectbox('Area', ['Urban','Metropolitan','Rural'])
category = st.sidebar.selectbox('Category', ['Electronics','Clothing','Groceries','Home'])

pickup_delay = st.sidebar.number_input('Pickup Delay (minutes)', min_value=0, max_value=1440, value=10)

if st.button('Predict Delivery Time'):
    dist = haversine(store_lat, store_lon, drop_lat, drop_lon)
    input_dict = {
        'Agent_Age': agent_age,
        'Agent_Rating': agent_rating,
        'Distance_km': dist,
        'Pickup_Delay_Minutes': pickup_delay,
        'Weather': weather,
        'Traffic': traffic,
        'Vehicle': vehicle,
        'Area': area,
        'Category': category,
        'Order_Hour': order_hour,
        'Order_Day': order_day
    }

    try:
        pred = predict_single(input_dict)
        st.success(f"Estimated delivery time: {pred:.2f} hours")
    except Exception as e:
        st.error(f"Prediction failed: {e}")