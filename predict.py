# Load saved model + scaler + encoders and provide a predict function for single examples

import joblib
import pandas as pd

MODEL_PATH = 'best_model.pkl'
SCALER_PATH = 'scaler.pkl'
ENC_PATH = 'encoders.pkl'

model = joblib.load(MODEL_PATH)
scaler = joblib.load(SCALER_PATH)
encoders = joblib.load(ENC_PATH)

# features order used in training
FEATURE_ORDER = ['Agent_Age','Agent_Rating','Distance_km','Pickup_Delay_Minutes',
                 'Weather','Traffic','Vehicle','Area','Category','Order_Hour','Order_Day']

def preprocess_input(d: dict):
    # create a dataframe of single row
    df = pd.DataFrame([d], columns=FEATURE_ORDER)

    # encode categorical
    for c, le in (encoders or {}).items():
        if c in df.columns:
            df[c] = le.transform(df[c].astype(str))

    # scale
    df_scaled = scaler.transform(df)
    return df_scaled

def predict_single(d: dict):
    X = preprocess_input(d)
    pred = model.predict(X)
    return float(pred[0])

if __name__ == '__main__':
    example = {
        'Agent_Age': 30, 'Agent_Rating': 4.5, 'Distance_km': 5.2,
        'Pickup_Delay_Minutes': 10, 'Weather': 'Sunny','Traffic': 'Medium',
        'Vehicle': 'Bike', 'Area': 'Urban', 'Category': 'Electronics',
        'Order_Hour': 14, 'Order_Day': 'Monday'
    }
    print('Prediction:', predict_single(example))

